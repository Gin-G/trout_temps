// Builds the static pages that give this site something to rank for.
//
// The dashboard at / is one URL whose river names arrive over fetch, so there is
// nothing in it for "Big Thompson temperature" to match. This writes a page per
// river and a page per gage, each with the name in the URL, the title and the
// heading, and a month of real USGS readings in the markup — then a sitemap that
// lists every one of them.
//
//   node build/generate.mjs [--out dist] [--states co,mt] [--offline]
//
// Output is dist/, which the Dockerfile copies into the image alongside the
// hand-written pages.

import { mkdir, writeFile, cp, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { STATES, collectState, groupRivers, DAYS } from './usgs.mjs';
import { slugify } from './rivers.mjs';
import { collectPlaces } from './places.mjs';
import { gagePage, riverPage, statePage, riversIndexPage, placePage, placesIndexPage,
         placeAliasPage, ORIGIN, esc } from './templates.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const args = { out: path.join(ROOT, 'dist'), states: null, cache: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') args.out = path.resolve(argv[++i]);
    else if (argv[i] === '--states') args.states = argv[++i].split(',').map((s) => s.trim().toLowerCase());
    else if (argv[i] === '--cache') args.cache = path.resolve(argv[++i]);
  }
  return args;
}

async function write(outDir, relPath, contents) {
  const full = path.join(outDir, relPath);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, contents);
}

// Roll a river's gages up into one set of figures. Warmest and coldest are the
// extremes across the whole river; the average is over every gage-day, so a
// river with one gage reporting and five silent isn't skewed by the silence.
function aggregate(gages) {
  const withStats = gages.map((g) => g.stats).filter((s) => s && s.days);
  if (!withStats.length) return null;
  const warm = withStats.map((s) => s.warmestF).filter((v) => v != null);
  const cold = withStats.map((s) => s.coldestF).filter((v) => v != null);
  let sum = 0, n = 0;
  for (const s of withStats) {
    if (s.averageF == null) continue;
    sum += s.averageF * s.days;
    n += s.days;
  }
  // Days over the line are counted on the warmest gage: if any stretch of the
  // river broke 65, the river broke 65 that day.
  const byDate = new Map();
  for (const s of withStats) {
    for (const d of s.dailyHighs) {
      const prev = byDate.get(d.date);
      if (prev == null || d.f > prev) byDate.set(d.date, d.f);
    }
  }
  // If any gage on the river published a real daily maximum, the rolled-up
  // series is a series of maxima. Only when every one of them fell back to the
  // mean does the river page have to hedge.
  const highsFrom = withStats.some((s) => s.highsFrom === 'max') ? 'max' : 'mean';
  const lowsFrom = withStats.some((s) => s.lowsFrom === 'min') ? 'min' : 'mean';
  const dates = [...byDate.keys()].sort();
  const dailyHighs = dates.map((d) => ({ date: d, f: byDate.get(d) }));
  return {
    days: dates.length || Math.max(...withStats.map((s) => s.days)),
    warmestF: warm.length ? Math.max(...warm) : null,
    coldestF: cold.length ? Math.min(...cold) : null,
    averageF: n ? sum / n : null,
    daysOver65: dailyHighs.filter((d) => d.f >= 65).length,
    daysOver60: dailyHighs.filter((d) => d.f >= 60).length,
    dailyHighs,
    highsFrom,
    lowsFrom,
    lastDate: dates[dates.length - 1] || null,
  };
}

function sitemapXml(entries) {
  const today = new Date().toISOString().slice(0, 10);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by build/generate.mjs. Every river, gage and index page, so the
     crawler does not have to run JavaScript to find them. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.map((e) => `  <url>
    <loc>${ORIGIN}${e.loc}</loc>
    <lastmod>${e.lastmod || today}</lastmod>
    <changefreq>${e.changefreq || 'daily'}</changefreq>
    <priority>${e.priority}</priority>
  </url>`).join('\n')}
</urlset>
`;
}

// Sitemaps cap at 50,000 URLs / 50MB. We are well under, but splitting by kind
// keeps Search Console's coverage report readable per page type.
function sitemapIndexXml(files) {
  const today = new Date().toISOString().slice(0, 10);
  return `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${files.map((f) => `  <sitemap>
    <loc>${ORIGIN}/${f}</loc>
    <lastmod>${today}</lastmod>
  </sitemap>`).join('\n')}
</sitemapindex>
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const states = args.states
    ? STATES.filter((s) => args.states.includes(s.code))
    : STATES;
  if (!states.length) throw new Error('No matching states: ' + args.states);

  console.log(`Generating from ${states.length} state${states.length === 1 ? '' : 's'} into ${args.out}`);

  const collected = [];
  // Sequential on purpose: fifteen concurrent state-wide queries is a good way
  // to get throttled, and the whole build is still a couple of minutes.
  for (const st of states) {
    const t0 = Date.now();
    const { gages } = await collectState(st);
    const rivers = groupRivers(gages);
    for (const r of rivers) r.agg = aggregate(r.gages);
    const places = collectPlaces(gages);
    const withStats = gages.filter((g) => g.stats && g.stats.days).length;
    collected.push({
      code: st.code, name: st.name, slug: slugify(st.name),
      gages, rivers, places, gageCount: gages.length,
    });
    console.log(`  ${st.code}  ${String(gages.length).padStart(4)} gages  ${String(rivers.length).padStart(4)} rivers  `
      + `${String(places.length).padStart(4)} towns  `
      + `${String(withStats).padStart(4)} with ${DAYS}-day stats  (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
  }

  const urls = { index: [], river: [], gage: [], place: [] };
  let aliases = 0;
  let pages = 0;

  for (const state of collected) {
    const stateRef = { code: state.code, name: state.name, slug: state.slug };
    for (const river of state.rivers) {
      const riverPath = `/river/${state.slug}/${river.slug}/`;
      await write(args.out, path.join(riverPath, 'index.html'), riverPage(river, stateRef));
      urls.river.push({
        loc: riverPath,
        priority: river.gages.length > 1 ? '0.8' : '0.7',
        lastmod: river.agg?.lastDate || undefined,
      });
      pages++;
      for (const g of river.gages) {
        const gagePath = `/gage/${g.id}/`;
        await write(args.out, path.join(gagePath, 'index.html'),
          gagePage(g, { name: river.name, slug: river.slug }, stateRef, river.gages));
        urls.gage.push({ loc: gagePath, priority: '0.6', lastmod: g.stats?.lastDate || undefined });
        pages++;
      }
    }
    for (const place of state.places) {
      const placePath = `/near/${place.slug}-${state.code}/`;
      await write(args.out, path.join(placePath, 'index.html'), placePage(place, stateRef));
      urls.place.push({ loc: placePath, priority: '0.8' });
      pages++;
      // The towns this one absorbed keep their URLs but not their tables, and
      // stay out of the sitemap: they canonicalise to the page above.
      for (const alias of place.aliases || []) {
        const aliasPath = `/near/${alias.slug}-${state.code}/`;
        await write(args.out, path.join(aliasPath, 'index.html'), placeAliasPage(alias, place, stateRef));
        aliases++;
      }
    }
    await write(args.out, `rivers/${state.slug}/index.html`, statePage(stateRef, state.rivers, state.places));
    urls.index.push({ loc: `/rivers/${state.slug}/`, priority: '0.9', changefreq: 'daily' });
    pages++;
  }

  await write(args.out, 'rivers/index.html', riversIndexPage(collected));
  await write(args.out, 'near/index.html', placesIndexPage(collected));
  urls.index.unshift(
    { loc: '/', priority: '1.0', changefreq: 'hourly' },
    { loc: '/rivers/', priority: '0.9', changefreq: 'daily' },
    { loc: '/near/', priority: '0.9', changefreq: 'daily' },
  );
  pages += 2;

  await write(args.out, 'sitemap-pages.xml', sitemapXml(urls.index));
  await write(args.out, 'sitemap-rivers.xml', sitemapXml(urls.river));
  await write(args.out, 'sitemap-places.xml', sitemapXml(urls.place));
  await write(args.out, 'sitemap-gages.xml', sitemapXml(urls.gage));
  await write(args.out, 'sitemap.xml', sitemapIndexXml([
    'sitemap-pages.xml', 'sitemap-rivers.xml', 'sitemap-places.xml', 'sitemap-gages.xml',
  ]));

  // The hand-written parts of the site travel with the generated ones, so dist/
  // is the whole document root and the Dockerfile has one thing to copy.
  const statics = ['trout_temps.html', 'detail.html', 'logo.png', 'favicon.ico',
                   'social-card.png', 'robots.txt'];
  for (const f of statics) {
    if (existsSync(path.join(ROOT, f))) await cp(path.join(ROOT, f), path.join(args.out, f));
  }
  await cp(path.join(ROOT, 'vendor'), path.join(args.out, 'vendor'), { recursive: true });
  await cp(path.join(ROOT, 'assets'), path.join(args.out, 'assets'), { recursive: true });
  await cp(path.join(ROOT, 'trout_temps.html'), path.join(args.out, 'index.html'));

  const totalUrls = urls.index.length + urls.river.length + urls.gage.length + urls.place.length;
  console.log(`\n${pages + aliases} pages written, ${totalUrls} URLs in the sitemap.`);
  console.log(`  ${urls.river.length} river pages, ${urls.place.length} town pages, `
    + `${urls.gage.length} gage pages, ${urls.index.length} index pages.`);
  console.log(`  ${aliases} merged towns canonicalised onto a neighbour, not in the sitemap.`);
}

main().catch((e) => {
  console.error('\nBuild failed:', e.message);
  process.exit(1);
});
